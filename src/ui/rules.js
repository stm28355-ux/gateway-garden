// 遊び方（はじめの画面・部屋・対戦中の「遊び方」タブで同じものを出す）。ゲームの流れの図と、ルールの短いまとめ。
import { glossaryHtml } from './describe.js';

// ゲームの流れ：はじめ → （採集 → 手入れ → 開花）をラウンドの数だけ → おわり
export function cycleHtml() {
  const step = (cls, title, sub, body) => `<div class="cy-step ${cls}"><b>${title}</b>${sub ? `<small>${sub}</small>` : ''}<span>${body}</span></div>`;
  return `<div class="cycle" role="img" aria-label="ゲームの流れの図">
    ${step('cy-start', 'はじめ', '1回だけ', '場から始まりのカードを1枚ずつ招く（無料）')}
    <div class="cy-down">↓</div>
    <div class="cy-loop">
      <div class="cy-tag">1ラウンド（全部で8回・短めは6回）</div>
      <div class="cy-row">
        ${step('cy-pick', '① 採集フェーズ', '1人ずつ順番に', '束を1つ摘む（魔素3個）→ 場のカードを2枚まで招く（手元へ）')}
        <div class="cy-arrow">→</div>
        ${step('cy-react', '② 手入れフェーズ', '全員いっしょに', '手元のカードを庭に置く・同じ色の魔素で★を育てる・手入れ → 「このラウンドを終える」')}
        <div class="cy-arrow">→</div>
        ${step('cy-bloom', '③ 開花', '終えた人から', '庭の左上から順に開花 → 魔素は10個までに → お題を満たしたら順位の枠に名前')}
      </div>
      <div class="cy-back">↺ 次のラウンドへ（先番が次の人に移る）</div>
    </div>
    <div class="cy-down">↓</div>
    ${step('cy-end', 'おわり', '', '★の点 ＋ 実り ＋ お題の点 で順位を決める')}
  </div>`;
}

export function rulesHtml() {
  return `${cycleHtml()}
  <ul class="rule-list">
    <li><b>① 採集フェーズ（順番に）</b>：場の束を1つ摘む（3個の魔素が手に入る）。そのあと、手持ちの魔素で場のカードを2枚まで招ける（2枚目は値段に好きな色1が足される）。値段の「好きな色」はどの色で払ってもよい。摘む順は先番から。</li>
    <li><b>② 手入れフェーズ（全員同時）</b>：招いたカード（住人）を庭の空いたマスに置く（庭が埋まっていれば置き換え。置かずに2枚まで持っておける）。カードと同じ色の魔素で★を育てる（何回でも）。手入れの効果は1ラウンドに1回。ここで得た魔素はその場で使える。終えるまでは「1つ戻す」でやり直せる。ほかの人がしたことは、ラウンドが終わるまで見えない。</li>
    <li><b>③ 開花</b>：「このラウンドを終える」で、庭のカードが左上から順に開花する。持てる魔素は10個まで（あふれた分は選んで捨てる）。お題を満たしていれば、順位の枠に名前が入る（同じラウンドに満たした人は同じ順位。1位5点・2位3点・3位1点）。</li>
    <li>導きのカードは、摘み方を曲げる（おかわり・入れ替え）。強化のカードは、育てる魔素を減らす（0個まで）。</li>
    <li><b>おわり</b>：8ラウンド（短めは6）で終わり。カードの★ごとの点、実り、お題の点の合計で比べる。</li>
  </ul>
  <h3 class="rule-h">キーワード</h3>${glossaryHtml()}`;
}
