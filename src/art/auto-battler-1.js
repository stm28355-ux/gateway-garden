const cache = new Map();
export function autoBattlerArt(name, size = 96) {
  const r = ROWS[name];
  if (!r) return null;
  if (!cache.has(name)) {
    const g = grid(16);
    r.forEach((row, y) => [...row].forEach((ch, x) => { if (PALETTE[ch]) g.px1(x, y, PALETTE[ch]); }));
    cache.set(name, g);
  }
  return toSvg(cache.get(name), size);
}
